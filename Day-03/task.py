import os
from google.colab import userdata
from langchain_groq import ChatGroq

os.environ["GROQ_API_KEY"] = userdata.get("GROQ_API_KEY").strip()

llm = ChatGroq(
    model="openai/gpt-oss-120b",
    temperature=0.3
)
print("Groq setup completed!")

from langchain_core.prompts import ChatPromptTemplate, MessagesPlaceholder
from langchain_core.output_parsers import StrOutputParser

SYSTEM = """ROLE: You are the friendly assistant for Sweet Crumbs Home Bakery.

FACTS:
- Plum cake: Rs 500
- Chocolate cake: Rs 650
- Cupcake: Rs 80 each
- Orders need 24 hours' notice.
- Eggless versions are available.

RULES:
- Never promise a delivery time or place.
- If you don't know something, say "I'll check with the owner."
- Calculate totals carefully.
- Keep replies under 50 words.
- Reply in English or Telugu, matching the customer.
"""

prompt = ChatPromptTemplate.from_messages([
    ("system", SYSTEM),
    MessagesPlaceholder("history"),
    ("human", "{question}")
])
chain = prompt | llm | StrOutputParser()

history = []

print("Sweet Crumbs assistant is ready!")

def ask(question: str) -> str:
    answer = chain.invoke({
      "history": history,
      "question": question
    })
    history.extend([
        ("human", question),
        ("ai", answer)
    ])
    return answer
print(ask("Hi, I'm Ravi. Do you make eggless cakes?"))
print(ask("What is my name?"))

