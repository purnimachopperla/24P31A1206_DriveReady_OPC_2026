import csv

def run_tests(path="/content/test.csv"):
    with open(path, "r", encoding="utf-8-sig", newline="") as file:
       rows = list(csv.DictReader(file.readlines()[1:], skipinitialspace=True))
    passed = 0
    for row in rows:
      answer = chain.invoke({
          "history": [],
          "question": row["question"]
      })
      expected = row["must_include"]
      ok = expected.lower() in answer.lower()
      if ok:
        passed +=1
      print("PASS" if ok else "FAIL", "|", row["question"])
      print("Expected:", expected)
      print("Answer:", answer)
      print("-" * 50)
    print(f"\n{passed}/{len(rows)} tests passed")

run_tests()

